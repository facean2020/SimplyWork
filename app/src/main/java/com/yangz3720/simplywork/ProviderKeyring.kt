package com.yangz3720.simplywork

import android.content.SharedPreferences
import androidx.core.content.edit
import com.yangz3720.simplywork.infrastructure.model.ModelInfo
import com.yangz3720.simplywork.infrastructure.model.config.ModelConfig
import com.yangz3720.simplywork.infrastructure.model.config.ModelProviderPresets
import com.yangz3720.simplywork.infrastructure.model.config.ProviderAccount
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json

/**
 * Multi-provider keyring state: API keys of all providers coexist + the current selection (provider + model).
 * Persisted in SharedPreferences (plaintext, same level of safety as the original ModelConfig in v1).
 */
@Serializable
data class KeyringState(
    val accounts: List<ProviderAccount> = ModelProviderPresets.ALL,
    val activeId: String? = null,
    val activeModel: String = "",
    val timeoutMs: Long = 60_000L,
    /**
     * v1.1: auto-approval of non-destructive calls (the user set the policy that "only high-risk operations
     * require manual approval"). On **by default** in the product; destructive ones (`RegisteredTool.destructive`)
     * are unaffected by it and always show a dialog.
     */
    val autoApproveNonDestructive: Boolean = true,
    /**
     * v1.1: context lengths of the models the provider reported in /models, keyed by [KeyringLogic.contextKey].
     * Only real positive numbers are written -- recording a 0 or a guessed value would make "unknown" and
     * "known" impossible to tell apart again.
     */
    val modelContextTokens: Map<String, Int> = emptyMap(),
    /**
     * v1.9: whether each model accepts image input, keyed by [KeyringLogic.contextKey]. Recorded from the same
     * `/models` response as [modelContextTokens], so learning it costs no extra request.
     *
     * A stored value is the **final** answer (endpoint report, else the built-in `ModelVisionTable`, else false),
     * which is what the attach button needs. A model missing from this map is simply "not learned yet" and falls
     * back to the table at read time -- so a table update still reaches models the user never re-fetched.
     */
    val modelVision: Map<String, Boolean> = emptyMap(),
    /** v1.1: manual override of the context budget; null = automatic derivation (see `ContextBudget.resolve`). */
    val contextBudgetOverride: Int? = null
)

/**
 * Pure-functional transforms of [KeyringState] (JVM-testable): all return a new state and never touch storage.
 */
object KeyringLogic {

    private val json = Json { ignoreUnknownKeys = true }

    /**
     * One-time migration: old single-config [ModelConfig] (KEY_MODEL_CONFIG) -> keyring state.
     * If baseUrl matches a preset, that preset is filled in; otherwise it is registered as a custom
     * account. A missing/corrupt legacy record returns the default state.
     */
    fun migrateLegacy(legacyJson: String?): KeyringState {
        val defaults = KeyringState()
        if (legacyJson.isNullOrBlank()) return defaults
        val legacy = runCatching { json.decodeFromString(ModelConfig.serializer(), legacyJson) }
            .getOrNull()
            ?.takeIf { it.baseUrl.isNotBlank() && it.defaultModel.isNotBlank() }
            ?: return defaults
        val preset = ModelProviderPresets.matchBaseUrl(legacy.baseUrl)
        val account = if (preset != null) {
            preset.copy(apiKey = legacy.apiKey)
        } else {
            ProviderAccount(id = CUSTOM_LEGACY_ID, name = "自定义", baseUrl = legacy.baseUrl, apiKey = legacy.apiKey)
        }
        return defaults.copy(
            accounts = defaults.accounts
                .map { if (it.id == account.id) account else it }
                .let { if (preset == null) it + account else it },
            activeId = account.id,
            activeModel = legacy.defaultModel,
            timeoutMs = legacy.timeoutMs
        )
    }

    /** Saves a provider's API key. */
    fun withKey(state: KeyringState, accountId: String, apiKey: String): KeyringState =
        state.copy(accounts = state.accounts.map { if (it.id == accountId) it.copy(apiKey = apiKey.trim()) else it })

    /** Adds or updates a custom endpoint (the id is generated by the caller). */
    fun upsertCustom(state: KeyringState, account: ProviderAccount): KeyringState =
        if (state.accounts.any { it.id == account.id }) {
            state.copy(accounts = state.accounts.map { if (it.id == account.id) account else it })
        } else {
            state.copy(accounts = state.accounts + account)
        }

    /** Removes an account (the caller guarantees presets cannot be removed); removing the currently selected one clears the selection. */
    fun removeAccount(state: KeyringState, accountId: String): KeyringState =
        state.copy(
            accounts = state.accounts.filterNot { it.id == accountId },
            activeId = if (state.activeId == accountId) null else state.activeId,
            activeModel = if (state.activeId == accountId) "" else state.activeModel
        )

    /** Switches the current provider + model (dynamic selection in the chat UI top bar). */
    fun selectModel(state: KeyringState, accountId: String, model: String): KeyringState =
        state.copy(activeId = accountId, activeModel = model.trim())

    fun withTimeout(state: KeyringState, timeoutMs: Long): KeyringState =
        state.copy(timeoutMs = timeoutMs.coerceAtLeast(1_000L))

    /** v1.1: whether non-destructive calls are auto-approved. */
    fun withAutoApprove(state: KeyringState, enabled: Boolean): KeyringState =
        state.copy(autoApproveNonDestructive = enabled)

    /**
     * v1.1: batch-records the context lengths reported by the provider. One persist + one version bump
     * instead of one per model -- otherwise "fetch the model list once" would trigger dozens of runtime
     * rebuilds. Non-positive numbers are always discarded (see [KeyringState]).
     */
    fun withModelContexts(state: KeyringState, learned: Map<String, Int>): KeyringState {
        val usable = learned.filterValues { it > 0 }
        if (usable.isEmpty()) return state
        return state.copy(modelContextTokens = state.modelContextTokens + usable)
    }

    /** v1.1: manually specify the context budget; null or a non-positive value = back to automatic derivation. */
    fun withContextBudgetOverride(state: KeyringState, tokens: Int?): KeyringState =
        state.copy(contextBudgetOverride = tokens?.takeIf { it > 0 })

    /**
     * v1.9: record everything one `/models` response told us about a provider's models -- the context lengths and
     * the image capability together, in **one** persist + one version bump (the same reason [withModelContexts]
     * batches: a single "fetch the list" would otherwise trigger one runtime rebuild per model).
     */
    fun withModelCatalog(state: KeyringState, accountId: String, catalog: List<ModelInfo>): KeyringState {
        if (catalog.isEmpty()) return state
        val withContexts = withModelContexts(
            state,
            catalog.mapNotNull { info ->
                info.contextTokens?.let { contextKey(accountId, info.id) to it }
            }.toMap()
        )
        return withContexts.copy(
            modelVision = withContexts.modelVision +
                catalog.associate { contextKey(accountId, it.id) to it.supportsVision }
        )
    }

    /**
     * Cache key for model context. **Must include the provider**: models with the same name can have
     * different specs on different endpoints (the same `gpt-4o` via the official service and via a
     * third-party relay do not necessarily agree on context).
     */
    fun contextKey(accountId: String, modelId: String): String = "$accountId/$modelId"

    fun activeAccount(state: KeyringState): ProviderAccount? =
        state.accounts.firstOrNull { it.id == state.activeId }

    /** Current selection -> a usable [ModelConfig]; no selection/no model returns null (the runtime is unavailable). */
    fun toModelConfig(state: KeyringState): ModelConfig? {
        val account = activeAccount(state) ?: return null
        if (state.activeModel.isBlank()) return null
        return ModelConfig(
            baseUrl = account.baseUrl,
            apiKey = account.apiKey,
            defaultModel = state.activeModel,
            timeoutMs = state.timeoutMs
        )
    }

    const val CUSTOM_LEGACY_ID = "custom-legacy"
    const val CUSTOM_ID_PREFIX = "custom-"
}

/**
 * SharedPreferences persistence shell for [KeyringState]. Runs the legacy [KeyringLogic.migrateLegacy] on first read.
 */
class ProviderKeyring(private val prefs: SharedPreferences) {

    // Initialized before [state]: read() uses json during property initialization (an initialization-order trap).
    private val json = Json { ignoreUnknownKeys = true }

    var state: KeyringState = read()
        private set

    /** Applies a pure-functional transform result and persists it. */
    fun update(transform: (KeyringState) -> KeyringState) {
        state = transform(state)
        prefs.edit { putString(KEY_KEYRING, encode(state)) }
    }

    private fun read(): KeyringState {
        val raw = prefs.getString(KEY_KEYRING, null)
        if (raw != null) {
            return runCatching { json.decodeFromString(KeyringState.serializer(), raw) }
                .getOrElse { KeyringLogic.migrateLegacy(null) }
        }
        // First run: try to migrate the old single-config storage.
        val migrated = KeyringLogic.migrateLegacy(prefs.getString(KEY_LEGACY_MODEL_CONFIG, null))
        prefs.edit { putString(KEY_KEYRING, encode(migrated)) }
        return migrated
    }

    private fun encode(state: KeyringState): String =
        json.encodeToString(KeyringState.serializer(), state)

    companion object {
        const val KEY_KEYRING = "provider_keyring"
        const val KEY_LEGACY_MODEL_CONFIG = "model_config"
    }
}
